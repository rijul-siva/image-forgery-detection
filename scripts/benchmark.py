"""
Comparative Benchmark Engine: ORB vs. SIFT for PixelGuard.
Designed and maintained by Member C.

Executes head-to-head benchmarks comparing:
- Runtime / latency (feature extraction, matching, RANSAC, end-to-end)
- Keypoint density and candidate match counts
- Inlier yield and consensus stability
- Parameter estimation error margins
- False positive vulnerability on repetitive textures
"""

from __future__ import annotations

import json
import os
import sys
import time
from pathlib import Path
from typing import Dict, List

import cv2
import numpy as np
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from scripts.evaluate import evaluate_dataset


OUTPUTS_DIR = REPO_ROOT / "outputs"


def run_benchmark():
    OUTPUTS_DIR.mkdir(parents=True, exist_ok=True)
    print("\n===================================================================")
    print("      PIXELGUARD COMPARATIVE BENCHMARK: ORB vs. SIFT")
    print("===================================================================\n")

    # Run full evaluations for both detectors
    print(">> Running ORB benchmark...")
    orb_summary = evaluate_dataset("orb")

    print("\n>> Running SIFT benchmark...")
    sift_summary = evaluate_dataset("sift")

    # Build comparison summary table
    metrics = [
        ("Total Images Tested", orb_summary["total_test_images"], sift_summary["total_test_images"]),
        ("Accuracy", f"{orb_summary['classification_metrics']['accuracy']*100:.1f}%", f"{sift_summary['classification_metrics']['accuracy']*100:.1f}%"),
        ("Precision", f"{orb_summary['classification_metrics']['precision']*100:.1f}%", f"{sift_summary['classification_metrics']['precision']*100:.1f}%"),
        ("Recall", f"{orb_summary['classification_metrics']['recall']*100:.1f}%", f"{sift_summary['classification_metrics']['recall']*100:.1f}%"),
        ("F1-Score", orb_summary['classification_metrics']['f1_score'], sift_summary['classification_metrics']['f1_score']),
        ("True Positives (TP)", orb_summary['confusion_matrix']['true_positives'], sift_summary['confusion_matrix']['true_positives']),
        ("False Positives (FP)", orb_summary['confusion_matrix']['false_positives'], sift_summary['confusion_matrix']['false_positives']),
        ("Mean Rotation Error", f"{orb_summary['parameter_estimation_accuracy']['mean_theta_error_deg']}°", f"{sift_summary['parameter_estimation_accuracy']['mean_theta_error_deg']}°"),
        ("Mean Scale Error", f"{orb_summary['parameter_estimation_accuracy']['mean_scale_error_pct']}%", f"{sift_summary['parameter_estimation_accuracy']['mean_scale_error_pct']}%"),
        ("Mean Translation Error", f"{orb_summary['parameter_estimation_accuracy']['mean_trans_error_px']} px", f"{sift_summary['parameter_estimation_accuracy']['mean_trans_error_px']} px"),
        ("Mean Localization IoU", orb_summary['parameter_estimation_accuracy']['mean_localization_iou'], sift_summary['parameter_estimation_accuracy']['mean_localization_iou']),
        ("Mean Pipeline Latency", f"{orb_summary['performance']['mean_latency_ms']} ms", f"{sift_summary['performance']['mean_latency_ms']} ms"),
    ]

    df_comp = pd.DataFrame(metrics, columns=["Metric", "ORB", "SIFT"])
    print("\n" + "=" * 60)
    print("                HEAD-TO-HEAD BENCHMARK SUMMARY")
    print("=" * 60)
    print(df_comp.to_string(index=False))

    # Save to Markdown
    md_lines = [
        "# PixelGuard: ORB vs. SIFT Benchmark Comparison",
        "**Generated by:** Member C Benchmark Engine  ",
        "**Evaluation Dataset:** Standardized synthetic copy-move and negative architectural benchmark.  ",
        "",
        "## 1. Head-to-Head Performance Summary",
        "",
        "| Metric | ORB | SIFT | Empirical Observation |",
        "| :--- | :--- | :--- | :--- |",
    ]

    orb_fp = orb_summary['confusion_matrix']['false_positives']
    sift_fp = sift_summary['confusion_matrix']['false_positives']
    orb_acc = orb_summary['classification_metrics']['accuracy'] * 100
    sift_acc = sift_summary['classification_metrics']['accuracy'] * 100
    orb_scale = orb_summary['parameter_estimation_accuracy']['mean_scale_error_pct']
    sift_scale = sift_summary['parameter_estimation_accuracy']['mean_scale_error_pct']
    orb_theta = orb_summary['parameter_estimation_accuracy']['mean_theta_error_deg']
    sift_theta = sift_summary['parameter_estimation_accuracy']['mean_theta_error_deg']
    orb_lat = orb_summary['performance']['mean_latency_ms']
    sift_lat = sift_summary['performance']['mean_latency_ms']

    for m, o, s in metrics:
        analysis = ""
        if "Latency" in m:
            faster = "SIFT" if sift_lat < orb_lat else "ORB"
            analysis = f"{faster} was faster on this dataset ({sift_lat} ms vs {orb_lat} ms)"
        elif "Recall" in m:
            analysis = "Share of forged images correctly detected"
        elif "False Positives" in m:
            analysis = f"ORB: {orb_fp}, SIFT: {sift_fp}"
        elif "Rotation" in m:
            analysis = f"SIFT {sift_theta}° vs ORB {orb_theta}°"
        elif "Scale" in m:
            analysis = f"SIFT {sift_scale}% vs ORB {orb_scale}%"
        elif "Precision" in m:
            analysis = f"Accuracy ORB {orb_acc:.1f}% vs SIFT {sift_acc:.1f}%"
        md_lines.append(f"| **{m}** | {o} | {s} | {analysis} |")

    md_lines.extend([
        "",
        "## 2. Key Findings & Engineering Tradeoffs",
        "",
        f"1. **Detection Accuracy & Texture Discrimination:** SIFT reached {sift_acc:.1f}% accuracy with {sift_fp} false positives on the negative set, while ORB reached {orb_acc:.1f}% with {orb_fp}. Repeated architectural textures (windows, bricks) share one dominant displacement, which the lattice-suppression filter removes before RANSAC; residual differences reflect descriptor discriminability.",
        f"2. **Rotational & Scale Stability:** Mean rotation error was {sift_theta}° (SIFT) vs {orb_theta}° (ORB); mean scale error {sift_scale}% vs {orb_scale}%.",
        f"3. **Computational Latency:** Mean end-to-end pipeline latency was {sift_lat} ms (SIFT) vs {orb_lat} ms (ORB) on the benchmark images.",
        "",
    ])

    out_benchmark_md = OUTPUTS_DIR / "benchmark_comparison.md"
    with open(out_benchmark_md, "w", encoding="utf-8") as f:
        f.write("\n".join(md_lines))
    print(f"\n[OK] Benchmark report saved to {out_benchmark_md}")

    # Also save CSV
    out_csv = OUTPUTS_DIR / "benchmark_summary.csv"
    df_comp.to_csv(out_csv, index=False)
    print(f"[OK] Benchmark CSV saved to {out_csv}\n")


if __name__ == "__main__":
    run_benchmark()
